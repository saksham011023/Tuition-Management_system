/* ──────────────────────────────────────────────
   Layout Component
   ────────────────────────────────────────────── */

export default function DashboardLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  const pathname = usePathname();
  const [sidebarOpen, setSidebarOpen] = useState(false);
  const [searchOpen, setSearchOpen] = useState(false);
  const { user, logout } = useAuth();

  useEffect(() => {
    function handleKeyDown(e: KeyboardEvent) {
      if ((e.metaKey || e.ctrlKey) && e.key === "k") {
        e.preventDefault();
        setSearchOpen((prev) => !prev);
      }
    }
    window.addEventListener("keydown", handleKeyDown);
    return () => window.removeEventListener("keydown", handleKeyDown);
  }, []);

  return (
    <ProtectedRoute>
      <div className="flex h-screen overflow-hidden" style={{ background: "var(--background)" }}>
        {/* Skip to Main Content Link for Keyboard Accessibility */}
        <a
          href="#main-content"
          className="sr-only focus:not-sr-only focus:absolute focus:top-4 focus:left-4 focus:z-50 focus:px-4 focus:py-2 focus:bg-indigo-600 focus:text-white focus:rounded-lg focus:shadow-lg focus:font-medium focus:text-sm"
        >
          Skip to main content
        </a>

        {/* ── Mobile overlay ── */}
        {sidebarOpen && (
          <div
            className="fixed inset-0 z-40 bg-black/50 backdrop-blur-sm lg:hidden"
            onClick={() => setSidebarOpen(false)}
          />
        )}

        {/* ── Sidebar ── */}
        <aside
          className={`
            fixed inset-y-0 left-0 z-50 flex flex-col
            w-[var(--sidebar-width)] transform transition-transform duration-300 ease-in-out
            lg:relative lg:translate-x-0
            ${sidebarOpen ? "translate-x-0" : "-translate-x-full"}
          `}
          style={{ backgroundColor: "var(--sidebar-bg)" }}
        >
          {/* Logo */}
          <div className="flex items-center gap-3 px-5 h-16 flex-shrink-0 border-b border-white/10">
            <div
              className="w-9 h-9 rounded-xl flex items-center justify-center text-white text-base font-bold shadow-lg flex-shrink-0"
              style={{ background: "var(--gradient-primary)" }}
            >
              🎓
            </div>
            <div className="flex flex-col min-w-0">
              <span className="text-white font-bold text-sm tracking-tight truncate">
                Excellence
              </span>
              <span className="text-[10px] text-indigo-300 font-medium tracking-wide truncate">
                Tuition Classes
              </span>
            </div>
          </div>

          {/* Navigation */}
          <nav className="flex-1 px-3 py-4 space-y-1 overflow-y-auto" role="navigation" aria-label="Main Navigation">
            {navItems.map((item) => {
              const isActive =
                item.href === "/dashboard"
                  ? pathname === "/dashboard"
                  : pathname.startsWith(item.href);

               return (
                <Link
                  key={item.href}
                  href={item.href}
                  onClick={() => setSidebarOpen(false)}
                  aria-current={isActive ? "page" : undefined}
                  className={`
                    group flex items-center gap-3 px-3 py-2.5 rounded-lg text-sm font-medium
                    transition-all duration-200
                    ${
                      isActive
                        ? "text-white"
                        : "hover:bg-white/5"
                    }
                  `}
                  style={{
                    color: isActive ? "#fff" : "var(--sidebar-fg)",
                    backgroundColor: isActive ? "var(--sidebar-active)" : undefined,
                  }}
                >
                  <span
                    className={`transition-transform duration-200 ${
                      isActive ? "" : "group-hover:scale-110"
                    }`}
                  >
                    {item.icon}
                  </span>
                  {item.label}
                </Link>
              );
            })}
          </nav>

          {/* User section with Logout */}
          <div className="px-4 py-4 border-t border-white/10 flex items-center justify-between gap-3">
            <div className="flex items-center gap-3 min-w-0">
              <div
                className="w-9 h-9 rounded-full flex items-center justify-center text-white text-xs font-bold uppercase shrink-0"
                style={{ background: "var(--gradient-purple)" }}
              >
                {user?.name ? user.name.substring(0, 2) : "ET"}
              </div>
              <div className="flex-1 min-w-0">
                <p className="text-sm font-medium text-white truncate">
                  {user?.name || "Teacher Account"}
                </p>
                <p className="text-[10px] font-semibold text-indigo-300 truncate uppercase tracking-wider">
                  {user?.role || "Teacher"}
                </p>
              </div>
            </div>

            <button
              onClick={logout}
              title="Sign Out"
              className="p-2 rounded-lg text-slate-400 hover:text-red-400 hover:bg-white/10 transition-colors cursor-pointer"
              aria-label="Logout"
            >
              <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24" strokeWidth={1.5}>
                <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 9V5.25A2.25 2.25 0 0013.5 3h-6a2.25 2.25 0 00-2.25 2.25v13.5A2.25 2.25 0 007.5 21h6a2.25 2.25 0 002.25-2.25V15m3 0l3-3m0 0l-3-3m3 3H9" />
              </svg>
            </button>
          </div>
        </aside>

        {/* ── Main content ── */}
        <div className="flex-1 flex flex-col min-w-0">
          {/* Topbar */}
          <header
            className="flex items-center justify-between px-6 flex-shrink-0 border-b"
            style={{
              height: "var(--topbar-height)",
              backgroundColor: "var(--card-bg)",
              borderColor: "var(--card-border)",
            }}
          >
            {/* Mobile menu button */}
            <button
              onClick={() => setSidebarOpen(true)}
              className="lg:hidden p-2 -ml-2 rounded-lg transition-colors hover:bg-slate-100 dark:hover:bg-slate-800"
              aria-label="Open sidebar"
            >
              <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={1.5} className="w-6 h-6">
                <path strokeLinecap="round" strokeLinejoin="round" d="M3.75 6.75h16.5M3.75 12h16.5m-16.5 5.25h16.5" />
              </svg>
            </button>

            {/* Page title */}
            <h1
              className="text-lg font-semibold hidden lg:block"
              style={{ color: "var(--text-primary)" }}
            >
              {navItems.find(
                (i) =>
                  i.href === "/dashboard"
                    ? pathname === "/dashboard"
                    : pathname.startsWith(i.href)
              )?.label || "Dashboard"}
            </h1>

            {/* Right side */}
            <div className="flex items-center gap-3">
              {/* Notification bell */}
              <NotificationBell />

              {/* Search */}
              <div
                onClick={() => setSearchOpen(true)}
                className="hidden md:flex items-center gap-2 px-3 py-1.5 rounded-lg border text-sm cursor-pointer hover:bg-slate-50/50 dark:hover:bg-slate-800/30 transition-all duration-150"
                style={{
                  borderColor: "var(--card-border)",
                  color: "var(--text-tertiary)",
                }}
              >
                <svg viewBox="0 0 20 20" fill="currentColor" className="w-4 h-4">
                  <path fillRule="evenodd" d="M9 3.5a5.5 5.5 0 1 0 0 11 5.5 5.5 0 0 0 0-11ZM2 9a7 7 0 1 1 12.452 4.391l3.328 3.329a.75.75 0 1 1-1.06 1.06l-3.329-3.328A7 7 0 0 1 2 9Z" clipRule="evenodd" />
                </svg>
                <span>Search...</span>
                <kbd className="hidden lg:inline text-xs px-1.5 py-0.5 rounded border font-sans" style={{ borderColor: "var(--card-border)" }}>
                  ⌘K
                </kbd>
              </div>

              {/* Logout Header Button */}
              <button
                onClick={logout}
                className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold text-red-500 hover:bg-red-50 dark:hover:bg-red-950/30 border border-red-200 dark:border-red-900/40 transition-colors cursor-pointer"
                title="Logout"
              >
                <svg className="w-4 h-4" fill="none" stroke="currentColor" viewBox="0 0 24 24" strokeWidth={1.5}>
                  <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 9V5.25A2.25 2.25 0 0013.5 3h-6a2.25 2.25 0 00-2.25 2.25v13.5A2.25 2.25 0 007.5 21h6a2.25 2.25 0 002.25-2.25V15m3 0l3-3m0 0l-3-3m3 3H9" />
                </svg>
                <span>Logout</span>
              </button>
            </div>

            {/* Search modal overlay */}
            <SearchModal isOpen={searchOpen} onClose={() => setSearchOpen(false)} />
          </header>

          {/* Page content */}
          <main id="main-content" className="flex-1 overflow-y-auto p-6" tabIndex={-1}>
            <ErrorBoundary>
              {children}
            </ErrorBoundary>
          </main>
        </div>
      </div>
    </ProtectedRoute>
  );
}

